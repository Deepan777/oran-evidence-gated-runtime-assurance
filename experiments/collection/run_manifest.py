#!/usr/bin/env python3
"""Resumable manifest-driven live collection orchestrator.

This runner executes only immutable rows generated by
``generate_protocol_manifests.py``. A row is accepted into the manifest only
when its broker reached the exact requested sample duration and every required
one-second radio-clock record is complete.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]


def _complete(
    evidence: Path, expected_rows: int, expected: dict[str, str] | None = None
) -> bool:
    summary, clock = evidence / "records.summary.json", evidence / "radio-clock-status.json"
    if not summary.is_file() or not clock.is_file():
        return False
    # Interrupted attempts can leave a zero-byte or partial clock file. Treat
    # that as an incomplete row so the launcher can archive the old evidence
    # and retry the immutable run, rather than aborting the whole manifest
    # with a JSONDecodeError.
    try:
        record = json.loads(summary.read_text(encoding="utf-8"))
        duration = json.loads(clock.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError, TypeError, ValueError):
        return False
    outage_aware = bool(
        expected is not None
        and expected.get("ACCEPTANCE_PROFILE") == "observed_outage_censoring_v1"
    )
    accepted_rows = (
        record.get("evidence_complete_rows") if outage_aware else record.get("complete_rows")
    )
    complete = (
        duration.get("status") == "PASS"
        and record.get("rows") == expected_rows
        and accepted_rows == expected_rows
        and record.get("radio_window_covered_rows") == expected_rows
        and (evidence / "records.parquet").is_file()
    )
    if not complete:
        return False
    if expected is not None and int(expected.get("REQUIRE_PROTECTED_TRAFFIC") or 0) == 1:
        traffic_path = evidence / "protected-traffic-status.json"
        if not traffic_path.is_file():
            return False
        try:
            traffic = json.loads(traffic_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError, TypeError, ValueError):
            return False
        if (
            traffic.get("status") != "PASS"
            or traffic.get("run_id") != expected.get("run_id")
            or traffic.get("expected_radio_windows") != expected_rows
            or traffic.get("complete_radio_windows") != expected_rows
            or not traffic.get("service_session_verified", False)
        ):
            return False
    # A completed radio clock is not, by itself, valid experimental evidence.
    # The broker can deliberately keep a failed virtual radio moving with
    # synthetic downlink clock-fill or zero-IQ uplink frames.  Those recovery
    # modes are useful for diagnosis, but accepting them into the locked live
    # dataset would silently turn an infrastructure failure into a result.
    status_path = evidence / "broker_status.jsonl"
    if not status_path.is_file():
        return False
    try:
        statuses = [
            json.loads(line)
            for line in status_path.read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]
    except (OSError, json.JSONDecodeError, TypeError, ValueError):
        return False
    if not statuses:
        return False
    if any(
        int(status.get("downlink_clock_fill_frames", 0)) > 0
        or int(status.get("uplink_silence_frames", 0)) > 0
        for status in statuses
    ):
        return False
    # Live controller development/confirmatory rows are not accepted merely
    # because the radio clock completed.  A failed xApp would otherwise look
    # like a valid training run and fail much later during replay assembly.
    metadata_path = evidence / "run_metadata.json"
    metadata: dict[str, Any] | None = None
    if metadata_path.is_file():
        try:
            metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError, TypeError, ValueError):
            return False
        if int(metadata.get("live_xapp_enabled", 0)) == 1:
            decisions_path = evidence / "live-xapp-decisions.jsonl"
            if not decisions_path.is_file():
                return False
            try:
                has_decision = any(
                    json.loads(line).get("status") == "DECISION"
                    for line in decisions_path.read_text(encoding="utf-8").splitlines()
                    if line.strip()
                )
            except (OSError, json.JSONDecodeError, TypeError, ValueError):
                return False
            if not has_decision:
                return False
    if expected is not None:
        if metadata is None:
            return False
        if metadata.get("run_id") != expected.get("run_id"):
            return False
        if metadata.get("scenario_id") != expected.get("scenario_id"):
            return False
        if expected.get("UE_IMAGE") and metadata.get("ue_image") != expected.get("UE_IMAGE"):
            return False
        if expected.get("ACCEPTANCE_PROFILE") and metadata.get("acceptance_profile") != expected.get("ACCEPTANCE_PROFILE"):
            return False
        expected_xapp = int(expected.get("ENABLE_LIVE_XAPP") or 0)
        if int(metadata.get("live_xapp_enabled", 0)) != expected_xapp:
            return False
        if expected_xapp:
            if metadata.get("live_xapp_controller_kind") != expected.get("CONTROLLER_KIND"):
                return False
            decisions_path = evidence / "live-xapp-decisions.jsonl"
            try:
                decisions = [
                    json.loads(line)
                    for line in decisions_path.read_text(encoding="utf-8").splitlines()
                    if line.strip()
                ]
            except (OSError, json.JSONDecodeError, TypeError, ValueError):
                return False
            if len(decisions) != expected_rows:
                return False
            if any(item.get("status") != "DECISION" for item in decisions):
                return False
            if any(
                not item.get("decision", {}).get("execution", {}).get("acknowledged", False)
                or item.get("decision", {}).get("execution", {}).get("failure") is not None
                for item in decisions
            ):
                return False
            if int(expected.get("LIVE_XAPP_XAI") or 0) == 1:
                xai_path = evidence / "live-xapp-xai.jsonl"
                if not xai_path.is_file():
                    return False
                try:
                    explanations = [
                        json.loads(line)
                        for line in xai_path.read_text(encoding="utf-8").splitlines()
                        if line.strip()
                    ]
                except (OSError, json.JSONDecodeError, TypeError, ValueError):
                    return False
                if len(explanations) != expected_rows:
                    return False
                if [item.get("window_index") for item in explanations] != list(range(expected_rows)):
                    return False
                allowed_xai_statuses = {
                    "XAI_COMPLETE", "XAI_NOT_APPLICABLE_SINGLE_FEASIBLE_ACTION",
                }
                if any(item.get("status") not in allowed_xai_statuses for item in explanations):
                    return False
    return True


def _payload(manifest: Path, rows: list[dict[str, str]], accepted: list[str], attempted: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "schema_version": 2,
        "manifest": str(manifest),
        "record_files": accepted,
        "attempted": attempted,
        "accepted_count": len(accepted),
        "expected_count": len(rows),
        "remaining": len(rows) - len(accepted),
    }


def _write_payload(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    temporary.replace(path)


def _environment(
    row: dict[str, str], config: dict[str, Any], image: str, ue_image: str,
    gnb_config: str, max_wall: int
) -> dict[str, str]:
    traffic = config["traffic_mbps"][row["traffic_load"]]
    environment = {
        **os.environ,
        "RUN_ID": row["run_id"], "SCENARIO_ID": row["scenario_id"], "JAMMER": row["jammer_type"],
        "JSR_DB": row["jsr_db"] or "0", "SEED": row["seed"], "TRAFFIC_LOAD": row["traffic_load"],
        "SERVICE_MIX": row["service_mix"], "ATTENUATION_DB": str(config["attenuation_db"][row["attenuation"]]),
        "RUN_SECONDS": row["run_length_seconds"], "PRE_JAM_SECONDS": row["pre_jam_seconds"],
        "JAMMER_ON_SECONDS": row["jammer_on_seconds"], "RECOVERY_SECONDS": row["recovery_seconds"],
        "PROTECTED_MBPS": str(traffic["protected"]),
        "BACKGROUND_MBPS": str(traffic["background"] if row["service_mix"] == "protected_plus_background" else 0),
        "EVIDENCE_CLASS": row["evidence_class"], "GNB_IMAGE": image,
        "UE_IMAGE": ue_image,
        "GNB_CONFIG": gnb_config,
        "MAX_WALL_SECONDS": str(max_wall),
        "REQUIRE_COMPLETE_TELEMETRY": "0" if row.get("ACCEPTANCE_PROFILE") == "observed_outage_censoring_v1" else "1",
        "REQUIRE_EVIDENCE_COMPLETE": "1" if row.get("ACCEPTANCE_PROFILE") == "observed_outage_censoring_v1" else "0",
        "ACCEPTANCE_PROFILE": row.get("ACCEPTANCE_PROFILE") or "strict_complete_telemetry_v1",
        "REQUIRE_PROTECTED_TRAFFIC": row.get("REQUIRE_PROTECTED_TRAFFIC") or "0",
    }
    # Development exploration rows may opt into the separately frozen live
    # detector/controller artifacts.  The immutable row remains the source of
    # every setting that crosses the sudo boundary.
    for name in (
        "ENABLE_LIVE_XAPP", "LIVE_XAPP_XAI", "DETECTOR_MODEL",
        "CONTROLLER_MODEL", "STATE_SCHEMA", "LIVE_XAPP_SELECTION_MODE",
        "LIVE_XAPP_FORCED_ACTION_ID", "CONTROLLER_KIND", "UE_TIMEOUT_MS",
        "OOD_GUARD_PROFILE",
    ):
        if row.get(name):
            environment[name] = row[name]
    return environment


def _sudo_environment(environment: dict[str, str]) -> list[str]:
    """Return only the immutable row variables that must cross ``sudo``.

    ``sudo`` intentionally resets arbitrary environment state.  Passing the
    complete parent environment would make a run non-reproducible (and could
    expose unrelated credentials); this allowlist makes the live collector's
    invocation auditable instead.
    """
    required = (
        "RUN_ID", "SCENARIO_ID", "JAMMER", "JSR_DB", "SEED", "TRAFFIC_LOAD",
        "SERVICE_MIX", "ATTENUATION_DB", "RUN_SECONDS", "PRE_JAM_SECONDS",
        "JAMMER_ON_SECONDS", "RECOVERY_SECONDS", "PROTECTED_MBPS",
        "BACKGROUND_MBPS", "EVIDENCE_CLASS", "GNB_IMAGE", "UE_IMAGE", "MAX_WALL_SECONDS",
        "REQUIRE_COMPLETE_TELEMETRY", "REQUIRE_EVIDENCE_COMPLETE", "ACCEPTANCE_PROFILE",
        "REQUIRE_PROTECTED_TRAFFIC",
        "ENABLE_LIVE_XAPP", "LIVE_XAPP_XAI",
        "DETECTOR_MODEL", "CONTROLLER_MODEL", "STATE_SCHEMA",
        "LIVE_XAPP_SELECTION_MODE", "LIVE_XAPP_FORCED_ACTION_ID", "CONTROLLER_KIND",
        "UE_TIMEOUT_MS", "GNB_CONFIG",
        "OOD_GUARD_PROFILE",
    )
    return [f"{name}={environment[name]}" for name in required if name in environment]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--protocol", type=Path, default=ROOT / "configs/experiments/protocol.yaml")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--limit", type=int, default=0, help="0 means all remaining rows")
    parser.add_argument("--max-wall-seconds", type=int, default=3600)
    parser.add_argument("--gnb-image", required=True)
    parser.add_argument("--ue-image", required=True)
    parser.add_argument("--gnb-config", default="ocudu_gnb_zmq_e2.yml")
    args = parser.parse_args()
    if args.limit < 0 or args.max_wall_seconds <= 0:
        parser.error("limit must be >= 0 and max-wall-seconds positive")
    config = yaml.safe_load(args.protocol.read_text(encoding="utf-8"))
    rows = list(csv.DictReader(args.manifest.open(encoding="utf-8", newline="")))
    accepted: list[str] = []
    attempted: list[dict[str, Any]] = []
    for row in rows:
        if row.get("UE_IMAGE") and row["UE_IMAGE"] != args.ue_image:
            raise SystemExit(
                f"manifest UE_IMAGE for {row['run_id']} does not match --ue-image"
            )
        evidence = ROOT / "results/raw" / f"iq-broker-live-{row['run_id']}"
        if _complete(evidence, int(row["run_length_seconds"]), row):
            accepted.append(str(evidence / "records.parquet"))
            _write_payload(args.output, _payload(args.manifest, rows, accepted, attempted))
            continue
        if args.limit and len(attempted) >= args.limit:
            break
        free_bytes = shutil.disk_usage(ROOT).free
        if free_bytes < 10 * 1024**3:
            attempted.append({
                "run_id": row["run_id"],
                "exit_code": 75,
                "accepted": False,
                "failure": "free disk below 10 GiB safety floor",
                "free_bytes": free_bytes,
            })
            _write_payload(args.output, _payload(args.manifest, rows, accepted, attempted))
            break
        environment = _environment(
            row, config, args.gnb_image, args.ue_image, args.gnb_config,
            args.max_wall_seconds,
        )
        result = subprocess.run(
            ["sudo", "env", *_sudo_environment(environment), "bash", "tools/run_live_pilot_scenario.sh"],
            cwd=ROOT, check=False,
        )
        valid = _complete(evidence, int(row["run_length_seconds"]), row)
        attempted.append({"run_id": row["run_id"], "exit_code": result.returncode, "accepted": valid})
        if valid:
            accepted.append(str(evidence / "records.parquet"))
        _write_payload(args.output, _payload(args.manifest, rows, accepted, attempted))
        if not valid:
            break  # preserve ordered, resumable execution after an evidence failure.
    payload = _payload(args.manifest, rows, accepted, attempted)
    _write_payload(args.output, payload)
    print(json.dumps(payload, indent=2))
    return 0 if not attempted or all(item["accepted"] for item in attempted) else 1


if __name__ == "__main__":
    raise SystemExit(main())
